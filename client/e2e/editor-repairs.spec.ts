import { test, expect, signUp, watchForErrors, expectNoPageErrors, reloadEditor } from './fixtures'
import JSZip from 'jszip'

test('ZIP editor selects, edits, scopes colours, follows page IDs, reloads and exports', async ({ page }) => {
  await signUp(page)
  const errors = watchForErrors(page)
  const zip = new JSZip()
  const markup = (title: string) => `<!doctype html><html><head><title>Repair school</title><link rel="stylesheet" href="site.css"></head><body><header><a href="index.html">Home</a><a href="about.html">About</a></header><main><h1>${title}</h1><p>Editable copy</p><img alt="Logo" src="logo.svg"><a class="btn" href="about.html">Learn more</a></main><footer>School footer</footer></body></html>`
  zip.file('index.html', markup('School home')); zip.file('about.html', markup('About school'))
  zip.file('site.css', 'body{margin:0;color:#222;background:white}header,footer{padding:20px;background:#eee}main{padding:30px}h1{color:#333}img{width:40px}')
  zip.file('logo.svg', '<svg xmlns="http://www.w3.org/2000/svg" width="40" height="40"><rect width="40" height="40" fill="red"/></svg>')
  await page.goto('/upload')
  await page.getByLabel('Your website file').setInputFiles({ name: 'school.zip', mimeType: 'application/zip', buffer: await zip.generateAsync({ type: 'nodebuffer' }) })
  await page.getByRole('button', { name: 'Open in the editor' }).click()
  const frame = page.frameLocator('iframe[title$="website canvas"]')
  await frame.locator('h1').click()
  await expect(page.getByLabel('Text', { exact: true })).toHaveValue('School home')
  await page.getByLabel('Text', { exact: true }).fill('Our school')
  await page.getByLabel('Text', { exact: true }).blur()
  await expect(frame.locator('h1')).toHaveText('Our school')
  await frame.locator('p').dblclick()
  await frame.locator('p').fill('Edited directly')
  await frame.locator('p').press('Enter')
  await expect(frame.locator('p')).toHaveText('Edited directly')
  await page.getByRole('button', { name: 'Colours', exact: true }).click()
  for (const [label, value] of [['Page background', '#123456'], ['Header background', '#abcdef']] as const) {
    await page.getByLabel(`${label} HEX value`).fill(value)
    await page.getByLabel(`${label} HEX value`).blur()
  }
  await expect(frame.locator('main')).toHaveCSS('background-color', 'rgb(18, 52, 86)')
  await expect(frame.locator('header')).toHaveCSS('background-color', 'rgb(171, 205, 239)')
  const tabs = await page.locator('.visual-panel-tabs').boundingBox()
  const controls = await page.locator('.visual-colors-scroll').boundingBox()
  expect(controls!.y).toBeGreaterThanOrEqual(tabs!.y + tabs!.height - 1)
  await page.getByRole('button', { name: 'Preview', exact: true }).click()
  await frame.locator('header a').filter({ hasText: 'About' }).click()
  await expect(frame.locator('h1')).toHaveText('About school')
  await expect(frame.locator('main')).not.toHaveCSS('background-color', 'rgb(18, 52, 86)')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: /Download/ }).click()
  const file = await download
  const stream = await file.createReadStream()
  const chunks: Buffer[] = []; for await (const chunk of stream!) chunks.push(Buffer.from(chunk))
  const exported = await JSZip.loadAsync(Buffer.concat(chunks))
  const home = await exported.file('index.html')!.async('string')
  expect(home).toContain('Our school'); expect(home).toContain('Edited directly'); expect(home).toContain('#123456')
  expect(home).not.toContain('href="page:')
  await reloadEditor(page)
  await expect(frame.locator('h1')).toHaveText('Our school')
  await expect(frame.locator('main')).toHaveCSS('background-color', 'rgb(18, 52, 86)')
  await page.goto('/templates?category=all')
  await expect(page.getByRole('region', { name: 'Imported templates' })).toContainText('Repair school')
  expectNoPageErrors(errors)
})
